#!/usr/bin/env node
/**
 * demo-app.md leg d8: "recorded numbers are parsed, not transcribed".
 *
 * Every grey reference value on the page is PARSED from
 * `docs/research/live/live-run-findings.md` at build time. One source. A stale
 * quote fails the build rather than ageing on screen — which is the difference
 * between a demo whose reference numbers are true and a demo whose reference
 * numbers were true once.
 *
 * If a pattern below stops matching, that is the point: the build stops, and a
 * human decides whether the finding changed or the demo did.
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = fileURLToPath(new URL('.', import.meta.url));
const SOURCE = join(here, '..', '..', '..', 'docs', 'research', 'live', 'live-run-findings.md');
const OUT = join(here, '..', 'src', 'reference-numbers.generated.ts');
const REL_SOURCE = 'docs/research/live/live-run-findings.md';

const text = readFileSync(SOURCE, 'utf8');
const lines = text.split('\n');

function grab(name, re, transform = (m) => m[1]) {
  for (let i = 0; i < lines.length; i++) {
    const m = re.exec(lines[i]);
    if (m) return { name, value: transform(m), line: i + 1 };
  }
  console.error(`\nleg d8 FAILED: no line in ${REL_SOURCE} matches the pattern for "${name}":\n  ${re}\n`);
  console.error('Either the finding changed and the demo must be updated, or the demo is quoting a');
  console.error('number that is no longer in the record. Both are build failures on purpose.\n');
  process.exit(1);
}

const found = [
  grab('coldStartNative', /cold start over HTTP.*?\|\s*\*\*([0-9.]+ s)\*\*/),
  grab('coldStartPeakRss', /cold start over HTTP.*?peak RSS ([0-9]+ MB)/),
  grab('warmResync', /warm re-sync \(mirror already folded\)\s*\|\s*\*\*([0-9.]+ s)\*\*/),
  grab('clientMirrorOnDisk', /client mirror on disk\s*\|\s*([0-9]+ MB) SQLite/),
  grab('events', /\*\*([0-9,]+) events, [0-9,]+ pool-active blocks/),
  grab('poolActiveBlocks', /\*\*[0-9,]+ events, ([0-9,]+) pool-active blocks/),
  grab('mainnetEpochs', /pool-active blocks, ([0-9]+) epochs, feed/),
  grab('mainnetFeedBytes', /epochs, feed ([0-9]+ MB), DB/),
  grab('storageWrites', /pool storage: writes \/ distinct slots\s*\|\s*([0-9,]+) \/ [0-9,]+/),
  grab('storageDistinctSlots', /pool storage: writes \/ distinct slots\s*\|\s*[0-9,]+ \/ ([0-9,]+)/),
  grab('anonymitySet', /\*\*([0-9,]+) notes\*\* \(the anonymity set\)/),
  grab('sepoliaDiscovery', /^in \*\*([0-9.]+ s)\*\*\./m),
  grab('abRequests', /request streams A vs B\s*\|\s*\*\*byte-identical\*\*: ([0-9,]+) requests/),
  grab('abBytes', /request streams A vs B\s*\|\s*\*\*byte-identical\*\*: [0-9,]+ requests, ([0-9,]+) bytes/),
  grab('sepoliaNoteBlock', /^\*\*([0-9,]+)\*\*, 3 STRK, registration \+ deposit/),
  grab('sepoliaSpendBlock', /A second transaction we made \(`0x[0-9a-f]+…`, block \*\*([0-9,]+)\*\*/),
];

// The one number the demo shows that is ARITHMETIC over parsed values, not a
// measurement. demo-app.md §6.3 requires it to be labelled as such and kept out
// of every live readout.
const epochs = Number(found.find((f) => f.name === 'mainnetEpochs').value);
const derived = {
  mainnetRequests: {
    value: String(1 + 1 + epochs + 1),
    formula: `1 genesis + 1 manifest + ${epochs} epochs + 1 head`,
  },
};

const body = `// GENERATED by scripts/parse-reference-numbers.mjs — do not edit.
//
// Every value here was PARSED from ${REL_SOURCE} at build time (demo-app.md leg
// d8). The line number each came from is carried with it so the page can point
// at the record rather than asking to be believed.
//
// Generated at build time from a file in this repository. No network involved.

export interface ReferenceNumber {
  readonly name: string;
  readonly value: string;
  readonly sourceLine: number;
}

export const REFERENCE_SOURCE = ${JSON.stringify(REL_SOURCE)};

export const REFERENCE: Record<string, ReferenceNumber> = {
${found.map((f) => `  ${f.name}: { name: ${JSON.stringify(f.name)}, value: ${JSON.stringify(f.value)}, sourceLine: ${f.line} },`).join('\n')}
};

/** Arithmetic over parsed values. NEVER shown in a live readout (§6.3). */
export const DERIVED: Record<string, { readonly value: string; readonly formula: string }> = ${JSON.stringify(derived, null, 2)};
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, body);
console.log(`leg d8: parsed ${found.length} reference values from ${REL_SOURCE}`);
for (const f of found) console.log(`  ${f.name.padEnd(22)} ${f.value.padEnd(14)} (line ${f.line})`);
